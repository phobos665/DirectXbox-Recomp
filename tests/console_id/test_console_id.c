/*
 * The console identity loader (src/kernel/xbox_console_id.c), on a made-up
 * EEPROM and hddinfo.txt written here: the checksums, and where each field
 * is read from. Portable; no real console's data.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "xbox_console_id.h"

#ifdef _WIN32
#include <direct.h>
#define SEP "\\"
static int make_dir(const char *p) { return _mkdir(p); }
static void set_env(const char *k, const char *v) { _putenv_s(k, v); }
#else
#include <sys/stat.h>
#define SEP "/"
static int make_dir(const char *p) { return mkdir(p, 0700); }
static void set_env(const char *k, const char *v) { setenv(k, v, 1); }
#endif

/* The loader looks beside the game folder by default; this test names the
 * folder outright, so the game folder is never asked for. */
int xbox_path_game_dir_utf8(char *out, size_t n)
{
    (void)out; (void)n;
    return 0;
}

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("FAIL %s:%d: ", __FILE__, __LINE__); \
    printf(__VA_ARGS__); printf("\n"); } } while (0)

static void put32(unsigned char *p, unsigned v)
{
    p[0] = (unsigned char)v; p[1] = (unsigned char)(v >> 8);
    p[2] = (unsigned char)(v >> 16); p[3] = (unsigned char)(v >> 24);
}

static unsigned get32(const unsigned char *p)
{
    return (unsigned)p[0] | (unsigned)p[1] << 8 | (unsigned)p[2] << 16 | (unsigned)p[3] << 24;
}

static void remove_in(const char *dir, const char *name)
{
    char path[700];
    snprintf(path, sizeof path, "%s" SEP "%s", dir, name);
    remove(path);
}

static int exists_in(const char *dir, const char *name)
{
    char path[700];
    FILE *f;
    snprintf(path, sizeof path, "%s" SEP "%s", dir, name);
    f = fopen(path, "rb");
    if (f)
        fclose(f);
    return f != NULL;
}

/* console_identity = generate: made once in <user dir>/console, the same
 * console on every load after, and never over anything already there. */
static void test_generated(const char *dir)
{
    char console[600], other[600], path[700];
    unsigned char ee[256], first[256];
    const XboxConsoleId *id;
    FILE *f;
    int i, digits = 1, zero_sec = 1;

    snprintf(console, sizeof console, "%s" SEP "user" SEP "console", dir);
    remove_in(console, "eeprom.bin");
    remove_in(console, "hd_key.txt");
    remove_in(console, "generated");
    set_env("RECOMP_CONSOLE_DIR", "");

    /* Not asked for: no console made, even with Xbox Live's network. */
    set_env("RECOMP_SYSLINK", "nat");
    set_env("RECOMP_CONSOLE_IDENTITY", "backup");
    xbox_console_id_reset();
    CHECK(xbox_ConsoleId() == NULL, "backup only, and there is none");
    CHECK(!exists_in(console, "eeprom.bin"), "nothing generated under backup");

    /* Looking only (the launcher's tab) never makes one, even under nat. */
    set_env("RECOMP_CONSOLE_IDENTITY", "");
    xbox_console_id_generate(0);
    xbox_console_id_reset();
    CHECK(xbox_ConsoleId() == NULL, "looking does not generate");
    CHECK(!exists_in(console, "eeprom.bin"), "nothing generated by looking");
    xbox_console_id_generate(-1);

    /* syslink = nat asks for it by default. */
    xbox_console_id_reset();
    id = xbox_ConsoleId();
    CHECK(id != NULL, "syslink = nat generates a console");
    if (!id)
        return;
    CHECK(id->generated, "marked generated");
    for (i = 0; i < 12; i++)
        digits &= id->serial[i] >= '0' && id->serial[i] <= '9';
    CHECK(digits, "serial is twelve digits");
    CHECK(id->mac[0] == 0x00 && id->mac[1] == 0x50 && id->mac[2] == 0xF2, "Microsoft's prefix");
    CHECK(id->have_hd_key && memcmp(id->hd_key, xbox_console_generated_hd_key, 16) == 0,
          "the shared HDD key");

    snprintf(path, sizeof path, "%s" SEP "eeprom.bin", console);
    f = fopen(path, "rb");
    CHECK(f && fread(ee, 1, 256, f) == 256, "eeprom.bin written whole");
    if (f)
        fclose(f);
    CHECK(get32(ee + 0x30) == xbox_eeprom_checksum(ee + 0x34, 0x2C), "factory checksum");
    CHECK(get32(ee + 0x60) == xbox_eeprom_checksum(ee + 0x64, 0x5C), "user checksum");
    for (i = 0; i < 0x30; i++)
        zero_sec &= ee[i] == 0;
    CHECK(zero_sec, "security section left zero");
    CHECK(!exists_in(console, "eeprom.bin.new") && !exists_in(console, "hd_key.txt.new"),
          "no temporary files left");
    memcpy(first, id->eeprom, 256);

    /* The same console on the next load, and a real console's key in
     * keys.ini does not get paired with it. */
    snprintf(path, sizeof path, "%s" SEP "user" SEP "keys.ini", dir);
    f = fopen(path, "w");
    if (f) {
        fprintf(f, "hd_key = 0123456789abcdeffedcba9876543210\n");
        fclose(f);
    }
    xbox_console_id_reset();
    id = xbox_ConsoleId();
    CHECK(id && memcmp(id->eeprom, first, 256) == 0, "stable across loads");
    CHECK(id && memcmp(id->hd_key, xbox_console_generated_hd_key, 16) == 0,
          "keys.ini's key not used for a generated console");
    remove(path);

    /* Nothing of a console's is ever written over. */
    CHECK(!xbox_console_generate(console), "refuses a folder with a console");
    snprintf(other, sizeof other, "%s" SEP "partial", dir);
    make_dir(other);
    remove_in(other, "eeprom.bin");
    snprintf(path, sizeof path, "%s" SEP "hd_key.txt", other);
    f = fopen(path, "w");
    if (f) {
        fprintf(f, "00112233445566778899aabbccddeeff\n");
        fclose(f);
    }
    CHECK(!xbox_console_generate(other), "refuses part of a backup");
    CHECK(!exists_in(other, "eeprom.bin"), "no eeprom.bin beside part of a backup");

    /* console_dir = off still means no console at all. */
    set_env("RECOMP_CONSOLE_DIR", "off");
    set_env("RECOMP_CONSOLE_IDENTITY", "generate");
    xbox_console_id_reset();
    CHECK(xbox_ConsoleId() == NULL, "console_dir = off");
    set_env("RECOMP_CONSOLE_DIR", "");
    set_env("RECOMP_CONSOLE_IDENTITY", "");
    set_env("RECOMP_SYSLINK", "");
}

int main(int argc, char **argv)
{
    unsigned char ee[256];
    char dir[512], path[600];
    const XboxConsoleId *id;
    FILE *f;
    int i;

    snprintf(dir, sizeof dir, "%s", argc > 1 ? argv[1] : "console_id_test");
    make_dir(dir);
    /* Before anything is looked up, so the player's own settings and
     * console are never read. */
    snprintf(path, sizeof path, "%s" SEP "user", dir);
    make_dir(path);
    set_env("RECOMP_USER_DIR", path);

    /* The known answer: an all-zero section sums to 0, complemented. */
    memset(ee, 0, sizeof ee);
    CHECK(xbox_eeprom_checksum(ee, 0x2C) == 0xFFFFFFFFu, "checksum of zeros");
    /* A carry out of the low dword is added back in. */
    put32(ee, 0xFFFFFFFFu);
    put32(ee + 4, 0x00000002u);
    CHECK(xbox_eeprom_checksum(ee, 8) == ~(0x00000001u + 1u), "checksum carry");

    /* A made-up console. */
    memset(ee, 0, sizeof ee);
    for (i = 0; i < 0x30; i++)
        ee[i] = (unsigned char)(0xA0 + i);            /* "encrypted" section */
    memcpy(ee + 0x34, "123456789012", 12);
    memcpy(ee + 0x40, "\x00\x12\x5A\x01\x02\x03", 6);
    for (i = 0; i < 16; i++)
        ee[0x48 + i] = (unsigned char)(0x10 + i);     /* online key */
    put32(ee + 0x58, 0x00400100u);                    /* video standard */
    put32(ee + 0x30, xbox_eeprom_checksum(ee + 0x34, 0x2C));
    ee[0x64] = 1;                                     /* something in the user section */
    put32(ee + 0x60, xbox_eeprom_checksum(ee + 0x64, 0x5C));

    snprintf(path, sizeof path, "%s" SEP "eeprom.bin", dir);
    f = fopen(path, "wb");
    fwrite(ee, 1, sizeof ee, f);
    fclose(f);
    snprintf(path, sizeof path, "%s" SEP "hddinfo.txt", dir);
    f = fopen(path, "w");
    fprintf(f, "Disk Serial Number : TESTSERIAL01\n"
               "Disk Model Number  : TEST DRIVE 8GB\n"
               "HDD Key            : (shown in a block EvoX writes)\n"
               "\n"
               "HDDLockDisablePassword 00 11 22 33 44 55 66 77 88 99 aa bb cc dd ee ff "
               "00 11 22 33 00 00 00 00 00 00 00 00 00 00 00 00\n"
               "\n"
               "XboxHDKey 01 23 45 67 89 ab cd ef fe dc ba 98 76 54 32 10\n");
    fclose(f);

    set_env("RECOMP_CONSOLE_DIR", dir);
    id = xbox_ConsoleId();
    CHECK(id != NULL, "a good EEPROM was not used");
    if (id) {
        static const unsigned char key[16] = { 0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef,
                                               0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10 };
        CHECK(memcmp(id->serial, "123456789012", 12) == 0, "serial");
        CHECK(memcmp(id->mac, "\x00\x12\x5A\x01\x02\x03", 6) == 0, "Ethernet address");
        CHECK(id->online_key[0] == 0x10 && id->online_key[15] == 0x1F, "online key");
        CHECK(id->have_hd_key && memcmp(id->hd_key, key, 16) == 0,
              "HDD key from XboxHDKey, not the lock password");
        CHECK(strcmp(id->disk_serial, "TESTSERIAL01") == 0, "disk serial '%s'", id->disk_serial);
        CHECK(strcmp(id->disk_model, "TEST DRIVE 8GB") == 0, "disk model '%s'", id->disk_model);
        CHECK(id->eeprom[0] == 0xA0, "the whole EEPROM kept");
        CHECK(!id->generated, "a backup is not a generated console");
    }

    test_generated(dir);

    if (failures) {
        printf("%d failure(s)\n", failures);
        return 1;
    }
    printf("console_id: all checks passed\n");
    return 0;
}
